#!/usr/bin/env python3
"""task227: user roof-deck family `roof_user_l{47,49}_user` (base 1.0x task definitions).

Why this family exists
----------------------
The v8 gate panel has two user roof decks (`task222_l47_roof_user`,
`task222_l49_roof_user`) that no collection cell ever used: the curriculum only had
`roof_l*_train_r7`, which is a different deck (AGENTS §8: changing the deck = a new
task family). The teacher wins with both user decks, but students only saw one human
recording, so the policy had no data to learn from.

This module writes the *base* task definitions only. The multiplier variants are
generated by `scripts/make_multiplier_tasks.py`, the single implementation of the
zombie-count ladder; no deck or playing rule is duplicated here.

Deck source
-----------
`scripts/pvz_tasks.py` `USER_DECKS`, which is also what gate v8 evaluates. L47 is
`[1,33,41,[48,1],39,44,37,4,17,30]` (Imitater -> sunflower); L49 is
`[1,33,39,44,4,2,17,35,14,15]`. `profile_for_deck` derives upgrade ownership and the
Imitater target; `terrain_covered` checks roof flower pot 33.

Seeds
-----
Training `84_000_000 + 2*2048` is a new block, disjoint from every manifest in
`configs/` and the main `artifacts/` tree (82M-92M was unused before task227).
Multiplier bands start at 84_100_000 + 100_000 x band, with 2048 seeds per level
offset from level 47.

The manifest is local only (artifacts/ is gitignored). Regenerate it before regenerating
`artifacts/stage4/multiplier_panel.json`:

  python3 scripts/make_user_roof_panel.py
  python3 scripts/make_multiplier_tasks.py --dry-run
  python3 scripts/make_multiplier_tasks.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'python'), str(ROOT / 'scripts')]

from pvz_tasks import USER_DECKS  # noqa: E402
from zone_panel import Zone, check_decks, task_document  # noqa: E402

LEVELS = (47, 49)
TRAIN_SEED_BASE = 84_000_000
TRAIN_SEEDS = 2048

ZONE = Zone(
    key='roof_user', task_prefix='roof_user_l', first_level=47, last_level=49, terrain='roof',
    default_out=ROOT / 'artifacts/task227/user_roof_panel.json',
    purpose='task227: user roof decks (L47 Imitater, L49), base 1.0x collection tasks',
)


def tasks() -> list[dict]:
    """One base training task per user roof level; the multiplier ladder is derived later."""
    result = []
    for index, level in enumerate(LEVELS):
        deck = USER_DECKS[level]
        problems = check_decks(ZONE, level, {f'roof_user_l{level}': deck})
        if problems:
            raise RuntimeError('deck is not admissible (AGENTS.md section 8):\n' + '\n'.join(problems))
        start = TRAIN_SEED_BASE + index * TRAIN_SEEDS
        task = task_document(ZONE, level, deck, f'roof_user_l{level}_user',
                             list(range(start, start + TRAIN_SEEDS)))
        assert task['level'] == level and task['terrain'] == 'roof'
        assert task['deck'] == list(deck) and task['zombie_count_multiplier'] == 1.0
        result.append(task)
    assert not set(result[0]['seeds']) & set(result[1]['seeds'])
    return result


def document() -> dict:
    return {
        'schema_version': 1,
        'split': 'stage4',
        'purpose': ZONE.purpose,
        'note': ('task227 new family; roof_l*_train_r7 unchanged (different deck, AGENTS section 8). '
                 'Deck comes from scripts/pvz_tasks.py USER_DECKS (also gate v8). No playing rule '
                 'and no card ranking is encoded here.'),
        'source': ('user recordings: L47 user_l47_5240981d44c6 (seed 116649463), '
                   'L49 user_l49_de02ad43d9b1 (seed 864551889); both verified wins in '
                   'MEMORY/docs/task222-gate-v8.md'),
        'seed_blocks': {'train': [TRAIN_SEED_BASE, TRAIN_SEED_BASE + len(LEVELS) * TRAIN_SEEDS - 1],
                        'multiplier_base': 84_100_000,
                        'multiplier_stride': 100_000},
        'tasks': tasks(),
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--out', type=Path, default=ZONE.default_out)
    p.add_argument('--dry-run', action='store_true')
    args = p.parse_args()
    doc = document()
    if args.dry_run:
        print(json.dumps(doc, ensure_ascii=False, indent=1))
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(doc, indent=1) + '\n')
    print(f'wrote {args.out}: ' + ', '.join(f"{t['task_id']} {len(t['seeds'])} seeds" for t in doc['tasks']))


if __name__ == '__main__':
    main()

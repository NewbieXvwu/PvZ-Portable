"""Regenerate CUDA ground-motion lookup tables from verified shipped reanimation data.

Build cuda/ReanimDump.cpp first. Its XML/compiled cross-check must pass before any table is emitted.
Only numerical x coordinates of the four supported walk clips are retained, not artwork.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--pak", type=Path, required=True)
    p.add_argument("--dump", type=Path, default=Path("build/reanim_dump"))
    p.add_argument("--out", type=Path, default=Path("cuda/AnimationTables.h"))
    args = p.parse_args()
    tracks = []
    for asset, clips in (("Zombie", ("anim_walk", "anim_walk2", "anim_superlongdeath")),
                         ("Zombie_polevaulter", ("anim_run", "anim_walk"))):
        output = subprocess.run([str(args.dump.resolve()), str(args.pak), asset, *clips],
                                capture_output=True, text=True, check=True).stdout
        if "IDENTICAL (0 field differences)" not in output:
            raise RuntimeError(f"{asset}: XML/compiled definitions did not verify")
        current = None
        for line in output.splitlines():
            match = re.match(r"== (\w+) .*mFrameStart=(\d+) mFrameCount=(\d+)", line)
            if match:
                current = {"name": asset + "_" + match[1], "start": int(match[2]),
                           "count": int(match[3]), "x": []}
                tracks.append(current)
            elif current:
                match = re.match(r"\s+(\d+)\s+[-+\d.eE]+\s+([-+\d.eE]+)\s", line)
                if match:
                    if int(match[1]) != current["start"] + len(current["x"]):
                        raise RuntimeError("non-contiguous ground table")
                    current["x"].append(float(match[2]))
        if any(len(t["x"]) != t["count"] for t in tracks):
            raise RuntimeError("short ground table")
    def literal(value):
        token = format(value, ".9g")
        return token + ("f" if "." in token or "e" in token else ".0f")
    lines = ["// Generated by scripts/cuda_animation_tables.py; numerical ground coordinates only.",
             "// main.pak SHA256: " + hashlib.sha256(args.pak.read_bytes()).hexdigest(),
             "#ifndef PVZ_ANIMATION_TABLES_H", "#define PVZ_ANIMATION_TABLES_H", "namespace pvzc {"]
    for index, track in enumerate(tracks):
        values = ", ".join(map(literal, track["x"]))
        lines += [f"// {track['name']}: start {track['start']}, count {track['count']}",
                  f"#define PVZ_GROUND_{index} {{ {values} }}",
                  f"inline constexpr float groundHost{index}[] = PVZ_GROUND_{index};",
                  "#ifdef __CUDACC__",
                  f"__device__ __constant__ float groundDevice{index}[] = PVZ_GROUND_{index};",
                  "#endif", f"#undef PVZ_GROUND_{index}"]
    lines += ["PVZ_SIM float GroundCoordinate(int type, int start, int frame) {",
              "#ifdef __CUDA_ARCH__"]
    for suffix in ("Device", "Host"):
        if suffix == "Host":
            lines.append("#else")
        for index, track in enumerate(tracks):
            condition = "type == 3" if "polevaulter" in track["name"] else "type != 3"
            lines.append(f"  if ({condition} && start == {track['start']} && frame >= 0 && "
                         f"frame < {track['count']}) return ground{suffix}{index}[frame];")
    lines += ["#endif", "  return 0.0f;", "}", "} // namespace pvzc", "#endif", ""]
    args.out.write_text("\n".join(lines))
    print(f"wrote {len(tracks)} clips / {sum(t['count'] for t in tracks)} x coordinates to {args.out}")


if __name__ == "__main__":
    main()

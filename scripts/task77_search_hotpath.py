#!/usr/bin/env python3
"""Offline task77 experiment driver; never changes collection defaults or queue state.

prepare freezes production tasks, weights, engine and Python source under ignored artifacts.
profile runs five terrains x four full teacher games with worker cProfile and SIGPROF.
All commands are generated by curriculum_queue.command_for.
"""
from __future__ import annotations

import argparse
import cProfile
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import time
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
MAIN = Path('/home/newbiexvwu/PvZ-search')
OUT = ROOT / 'artifacts/task77'
sys.path[:0] = [str(ROOT / 'scripts'), str(ROOT / 'python')]

CELLS = {
    'day': 'day_l7_train_d7_m125',
    'night': 'night_l14_train_n10_m125',
    'pool': 'pool_l24_train_p9k_m125',
    'conveyor': 'day_l10_orig_train_m125',
    'roof': 'roof_l41_train_r7',
    'fog': 'fog_user_l31_snow',
}


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n')


def prepare(args):
    if (args.out / 'freeze.json').exists():
        raise FileExistsError('freeze already exists; use the frozen inputs')
    from make_fog_user_panel import tasks as fog_tasks
    sources = [MAIN / 'artifacts/stage4/multiplier_panel.json',
               MAIN / '.claude/worktrees/redeploy/artifacts/task46/roof_panel.json']
    tasks = fog_tasks()
    for path in sources:
        tasks.extend(json.loads(path.read_text())['tasks'])
    selected = []
    for task_id in CELLS.values():
        task = next(t for t in tasks if t['task_id'] == task_id)
        selected.append(dict(task, seeds=task['seeds'][:8]))
    save(args.out / 'manifest.json', {'tasks': selected})
    files = {'engine': args.engine, 'student': args.student,
             'value': MAIN / 'artifacts/value_net/v5/model.pt',
             'static': MAIN / 'artifacts/hard/value_branch1/model.pt'}
    identities = {}
    for name, source in files.items():
        target = args.out / 'frozen' / ('pvz-portable' if name == 'engine' else name + '.pt')
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        identities[name] = {'source': str(source), 'path': str(target), 'sha256': digest(target)}
    for folder in ('python', 'scripts', 'src'):
        shutil.copytree(ROOT / folder, args.out / 'baseline' / folder,
                        ignore=shutil.ignore_patterns('__pycache__'))
    identities['manifest_sha256'] = digest(args.out / 'manifest.json')
    identities['git_head'] = subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip()
    save(args.out / 'freeze.json', identities)
    print(json.dumps(identities, indent=1))


_PLAY = None
_COMMAND = None
_PROFILE_DIR = None
_TIMES = {}


def measured_command(env, command):
    name = command.split()[0]
    start = time.perf_counter()
    result = _COMMAND(env, command)
    row = _TIMES.setdefault(name, {'calls': 0, 'wall_seconds': 0.0})
    row['calls'] += 1
    row['wall_seconds'] += time.perf_counter() - start
    return result


def profiled_play(job):
    import search_play
    _TIMES.clear()
    search_play._W['rollout_metrics'] = {}
    profiler = cProfile.Profile()
    started = time.perf_counter()
    try:
        result = profiler.runcall(_PLAY, job)
    finally:
        profiler.dump_stats(str(_PROFILE_DIR / f"{job['seed']}.pstats"))
    save(_PROFILE_DIR / f"{job['seed']}.json", {
        'game': result, 'wall_seconds': time.perf_counter() - started,
        'commands': _TIMES, 'rollout': search_play._W['rollout_metrics']})
    return result


def driver(argv):
    global _PLAY, _COMMAND, _PROFILE_DIR
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--profile-dir', type=Path, required=True)
    args, remaining = parser.parse_known_args(argv)
    sys.path[:0] = [str(args.source / 'scripts'), str(args.source / 'python')]
    import search_play
    from pvz_env import PvZEnv
    _PROFILE_DIR = args.profile_dir
    _PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    _PLAY, _COMMAND = search_play._play, PvZEnv._command
    search_play._play, PvZEnv._command = profiled_play, measured_command
    sys.argv = [str(args.source / 'scripts/search_play.py'), *remaining]
    search_play.main()


def command(args, cell, tag, games, beta=1.0, engine=None, source=None):
    from curriculum_queue import command_for
    frozen = json.loads((args.out / 'freeze.json').read_text())
    common = SimpleNamespace(
        python=Path(sys.executable), workers=args.workers,
        resource_dir=Path('/home/newbiexvwu/.cache/pvz-research-resources'),
        rollout_policy=Path(frozen['student']['path']), value=Path(frozen['value']['path']),
        static_value=Path(frozen['static']['path']),
        executable=engine or Path(frozen['engine']['path']))
    cmd = command_for(common, args.out / 'manifest.json', CELLS[cell], 0, games,
                      f'{cell}_{tag}', frames=args.out / tag / 'frames', out=args.out / tag,
                      beta=beta)
    if source is not None:
        cmd[1] = str(source / 'scripts/search_play.py')
    return cmd


def run(cmd, log):
    log.parent.mkdir(parents=True, exist_ok=True)
    print(shlex.join(cmd), flush=True)
    with log.open('a') as stream:
        subprocess.run(cmd, stdout=stream, stderr=subprocess.STDOUT, check=True,
                       env=dict(os.environ, PVZ_NO_POPUP='1', OMP_NUM_THREADS='1',
                                OPENBLAS_NUM_THREADS='1'))


def profile(args):
    frozen = json.loads((args.out / 'freeze.json').read_text())
    sampler = args.out / 'prof_sample.so'
    subprocess.run(['cc', '-shared', '-fPIC', '-O2', '-o', str(sampler),
                    str(ROOT / 'scripts/prof_sample.c'), '-ldl'], check=True)
    for cell in ('day', 'night', 'pool', 'fog', 'roof'):
        folder = args.out / 'profile' / cell
        folder.mkdir(parents=True, exist_ok=True)
        wrapper = folder / 'engine'
        wrapper.write_text('#!/bin/sh\nexport LD_PRELOAD=' + shlex.quote(str(sampler)) +
                           '\nexport PVZ_PROF_OUT=' + shlex.quote(str(folder)) + '/pcs.$$.bin\nexec ' +
                           shlex.quote(frozen['engine']['path']) + ' "$@"\n')
        wrapper.chmod(0o755)
        cmd = command(args, cell, 'profile', 4, engine=wrapper)
        cmd[1:2] = [str(Path(__file__).resolve()), 'driver', '--source', str(args.out / 'baseline'),
                    '--profile-dir', str(folder)]
        save(folder / 'command.json', cmd)
        run(cmd, folder / 'run.log')


def main():
    if len(sys.argv) > 1 and sys.argv[1] == 'driver':
        driver(sys.argv[2:])
        return
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('phase', choices=('prepare', 'profile'))
    parser.add_argument('--out', type=Path, default=OUT)
    parser.add_argument('--workers', type=int, choices=range(1, 5), default=4)
    parser.add_argument('--engine', type=Path, default=MAIN / '.claude/worktrees/cq/build4/pvz-portable')
    parser.add_argument('--student', type=Path, default=Path('/home/newbiexvwu/pvz-logs/curriculum_state.pipeline/round_000011/student/model.pt'))
    args = parser.parse_args()
    if not args.out.is_absolute():
        parser.error('--out must be absolute')
    {'prepare': prepare, 'profile': profile}[args.phase](args)


if __name__ == '__main__':
    main()

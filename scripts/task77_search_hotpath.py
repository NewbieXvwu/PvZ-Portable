def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n')


def prepare(args):
    if (args.out / 'freeze.json').exists():
        raise FileExistsError('freeze already exists; use the frozen inputs')
    from make_fog_user_panel import tasks as fog_tasks
    sources = [MAIN / 'artifacts/stage4/multiplier_panel.json',
               MAIN / '.claude/worktrees/redeploy/artifacts/task46/roof_panel.json']
    tasks = fog_tasks()
    for path in sources:
        tasks.extend(json.loads(path.read_text())['tasks'])
    selected = []
    for task_id in CELLS.values():
        task = next(t for t in tasks if t['task_id'] == task_id)
        selected.append(dict(task, seeds=task['seeds'][:8]))
    save(args.out / 'manifest.json', {'tasks': selected})
    files = {'engine': args.engine, 'student': args.student,
             'value': MAIN / 'artifacts/value_net/v5/model.pt',
             'static': MAIN / 'artifacts/hard/value_branch1/model.pt'}
    identities = {}
    for name, source in files.items():
        target = args.out / 'frozen' / ('pvz-portable' if name == 'engine' else name + '.pt')
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        identities[name] = {'source': str(source), 'path': str(target), 'sha256': digest(target)}
    for folder in ('python', 'scripts', 'src'):
        shutil.copytree(ROOT / folder, args.out / 'baseline' / folder,
                        ignore=shutil.ignore_patterns('__pycache__'))
    identities['manifest_sha256'] = digest(args.out / 'manifest.json')
    identities['git_head'] = subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip()
    save(args.out / 'freeze.json', identities)
    print(json.dumps(identities, indent=1))


_PLAY = None
_COMMAND = None
_PROFILE_DIR = None
_TIMES = {}


def process_cpu(env):
    if env._process is None:
        return 0.0
    fields = Path(f'/proc/{env._process.pid}/stat').read_text().rsplit(')', 1)[1].split()
    return (int(fields[11]) + int(fields[12])) / os.sysconf('SC_CLK_TCK')


def measured_command(env, command):
    name = command.split()[0]
    cpu_before = process_cpu(env)
    start = time.perf_counter()
    result = _COMMAND(env, command)
    elapsed = time.perf_counter() - start
    row = _TIMES.setdefault(name, {'calls': 0, 'wall_seconds': 0.0, 'engine_cpu_seconds': 0.0})
    row['calls'] += 1
    row['wall_seconds'] += elapsed
    row['engine_cpu_seconds'] += process_cpu(env) - cpu_before
    return result


def profiled_play(job):
    import search_play
    _TIMES.clear()
    search_play._W['rollout_metrics'] = {}
    profiler = cProfile.Profile()
    started = time.perf_counter()
    cpu_started = time.process_time()
    before = (_COMMAND(search_play._W['env'], 'ENV_PROFILE')
              if search_play._W.get('env') is not None else None)
    try:
        result = profiler.runcall(_PLAY, job)
    finally:
        profiler.dump_stats(str(_PROFILE_DIR / f"{job['seed']}.pstats"))
    save(_PROFILE_DIR / f"{job['seed']}.json", {
        'game': result, 'wall_seconds': time.perf_counter() - started,
        'worker_cpu_seconds': time.process_time() - cpu_started,
        'commands': _TIMES, 'rollout': search_play._W['rollout_metrics'],
        'engine_before': before, 'engine_after': _COMMAND(search_play._W['env'], 'ENV_PROFILE')})
    return result


def driver(argv):
    global _PLAY, _COMMAND, _PROFILE_DIR
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--profile-dir', type=Path, required=True)
    args, remaining = parser.parse_known_args(argv)
    sys.path[:0] = [str(args.source / 'scripts'), str(args.source / 'python')]
    import search_play
    from pvz_env import PvZEnv
    _PROFILE_DIR = args.profile_dir
    _PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    _PLAY, _COMMAND = search_play._play, PvZEnv._command
    search_play._play, PvZEnv._command = profiled_play, measured_command
    sys.argv = [str(args.source / 'scripts/search_play.py'), *remaining]
    search_play.main()


def command(args, cell, tag, games, beta=1.0, engine=None, source=None, offset=0):
    from curriculum_queue import command_for
    frozen = json.loads((args.out / 'freeze.json').read_text())
    common = SimpleNamespace(
        python=Path(sys.executable), workers=args.workers,
        resource_dir=Path('/home/newbiexvwu/.cache/pvz-research-resources'),
        rollout_policy=Path(frozen['student']['path']), value=Path(frozen['value']['path']),
        static_value=Path(frozen['static']['path']),
        executable=engine or Path(frozen['engine']['path']))
    cmd = command_for(common, args.out / 'manifest.json', CELLS[cell], offset, games,
                      f'{cell}_{tag}', frames=args.out / tag / 'frames', out=args.out / tag,
                      beta=beta)
    if source is not None:
        cmd[1] = str(source / 'scripts/search_play.py')
    return cmd


def run(cmd, log):
    log.parent.mkdir(parents=True, exist_ok=True)
    print(shlex.join(cmd), flush=True)
    with log.open('a') as stream:
        subprocess.run(cmd, stdout=stream, stderr=subprocess.STDOUT, check=True,
                       env=dict(os.environ, PVZ_NO_POPUP='1', OMP_NUM_THREADS='1',
                                OPENBLAS_NUM_THREADS='1'))


def profile(args):
    frozen = json.loads((args.out / 'freeze.json').read_text())
    sampler = args.out / 'prof_sample.so'
    subprocess.run(['cc', '-shared', '-fPIC', '-O2', '-o', str(sampler),
                    str(ROOT / 'scripts/prof_sample.c'), '-ldl'], check=True)
    for cell in ('day', 'night', 'pool', 'fog', 'roof'):
        tag = 'profile'
        folder = args.out / tag / cell
        previous = list(folder.glob('[0-9]*.json'))
        if len(previous) == 4:
            if all('worker_cpu_seconds' in json.loads(p.read_text()) for p in previous):
                print(f'{cell}: complete detailed profile exists', flush=True)
                continue
            # Early preflight profiles lacked engine counters. Preserve them; collect a
            # complete replacement with identical tasks/seeds, never overwrite evidence.
            tag = 'profile_complete'
            folder = args.out / tag / cell
        folder.mkdir(parents=True, exist_ok=True)
        wrapper = folder / 'engine'
        wrapper.write_text('#!/bin/sh\nexport LD_PRELOAD=' + shlex.quote(str(sampler)) +
                           '\nexport PVZ_PROF_OUT=' + shlex.quote(str(folder)) + '/pcs.$$.bin\nexec ' +
                           shlex.quote(frozen['engine']['path']) + ' "$@"\n')
        wrapper.chmod(0o755)
        cmd = command(args, cell, tag, 4, engine=wrapper)
        cmd[1:2] = [str(Path(__file__).resolve()), 'driver', '--source', str(args.out / 'baseline'),
                    '--profile-dir', str(folder)]
        save(folder / 'command.json', cmd)
        run(cmd, folder / 'run.log')


def profile_summary(args):
    import pstats
    from collections import Counter
    from prof_symbolize import load, symbolize
    evidence = {'cells': {}}
    frozen = json.loads((args.out / 'freeze.json').read_text())
    for cell in ('day', 'night', 'pool', 'fog', 'roof'):
        folder = args.out / 'profile_complete' / cell
        if not folder.is_dir():
            folder = args.out / 'profile' / cell
        paths = sorted(folder.glob('[0-9]*.json'))
        if len(paths) != 4:
            raise ValueError(f'{cell}: expected four complete profiles')
        totals = Counter()
        commands = Counter()
        cpu_commands = Counter()
        python_functions = Counter()
        for path in paths:
            data = json.loads(path.read_text())
            totals.update({'wall': data['wall_seconds'], 'worker_cpu': data['worker_cpu_seconds'],
                           'decisions': data['game']['decisions'], 'searches': data['game']['searched'],
                           'simulation': data['rollout']['simulation_seconds'],
                           'student': data['rollout']['network_seconds']})
            for name, timing in data['commands'].items():
                commands[name] += timing['wall_seconds']
                cpu_commands[name] += timing['engine_cpu_seconds']
            for slot, kind in enumerate(('leaf', 'static')):
                before = data['engine_before']
                for metric in ('features', 'forward', 'calls'):
                    delta = data['engine_after']['value'][slot][metric]
                    if before is not None:
                        delta -= before['value'][slot][metric]
                    totals[f'{kind}_{metric}'] += delta
            for (file, line, name), (_cc, _nc, tt, _ct, _callers) in pstats.Stats(str(path.with_suffix('.pstats'))).stats.items():
                # Self time excludes children, so categories here do not double count.
                python_functions[f'{Path(file).name}:{line}:{name}'] += tt
        components = {
            'rollout_simulation': totals['simulation'], 'cpp_student': totals['student'],
            'leaf_features_forward': totals['leaf_features'] + totals['leaf_forward'],
            'static_features_forward': totals['static_features'] + totals['static_forward'],
            'snapshot_explicit_roundtrip': sum(commands[k] for k in ('SNAPSHOT_FAST', 'RESTORE_FAST', 'DROP_SNAPSHOT_FAST')),
            'static_restore_action_ipc': commands['STATIC_SCORES'] - totals['static_features'] - totals['static_forward'],
            'rollout_restore_control_ipc': commands['ROLLOUT_VALUE'] - totals['simulation'] - totals['student'] - totals['leaf_features'] - totals['leaf_forward'],
            'other_commands': sum(v for k, v in commands.items() if k not in
                ('SNAPSHOT_FAST', 'RESTORE_FAST', 'DROP_SNAPSHOT_FAST', 'STATIC_SCORES', 'ROLLOUT_VALUE')),
            'python_outside_commands': totals['wall'] - sum(commands.values()),
        }
        counts = Counter()
        modules = {}
        for path in folder.glob('pcs.*.bin'):
            names, offsets, slots = load(path)
            for offset, slot in zip(offsets, slots):
                name = names[slot] if slot < len(names) else 'unknown'
                modules.setdefault(name, set()).add(offset)
                counts[name, offset] += 1
        functions = Counter()
        for name, offsets in modules.items():
            binary = Path(name)
            if binary.name == 'pvz-portable':
                binary = Path(frozen['engine']['path'])
            labels = symbolize(binary, list(offsets)) if binary.is_file() else {}
            for offset in offsets:
                functions[f'{Path(name).name}:{labels.get(offset, "unknown")}'] += counts[name, offset]
        evidence['cells'][cell] = {
            'profiles': [str(p) for p in paths], 'totals': dict(totals),
            'components_seconds': components,
            'milliseconds_per_decision': {k: v * 1000 / totals['decisions'] for k, v in components.items()},
            'commands_wall_seconds': dict(commands), 'commands_engine_cpu_seconds': dict(cpu_commands),
            'python_self_seconds': python_functions.most_common(25),
            'samples': sum(functions.values()), 'cpp_samples': functions.most_common(45)}
    save(args.out / 'profile_summary.json', evidence)
    print(json.dumps({k: v['milliseconds_per_decision'] for k, v in evidence['cells'].items()}, indent=1))


def compare_frames(old, new):
    """Compare complete ordered records, including labels/targets/verification and observations.

    Verification wall time is diagnostic, deliberately excluded from label identity.
    Dict float equality alone misses -0.0; canonical JSON retains that distinction.
    """
    def canonical(frame):
        frame = dict(frame)
        if frame.get('verification'):
            frame['verification'] = dict(frame['verification'])
            frame['verification'].pop('seconds', None)
        return json.dumps(frame, sort_keys=True, separators=(',', ':'), allow_nan=False)

    for index in range(max(len(old), len(new))):
        if index >= min(len(old), len(new)):
            return {'index': index, 'reason': 'length', 'old': len(old), 'new': len(new)}
        if canonical(old[index]) != canonical(new[index]):
            return {'index': index, 'reason': 'frame', 'fields': [
                key for key in old[index].keys() | new[index].keys()
                if canonical({key: old[index].get(key)}) != canonical({key: new[index].get(key)})]}
    return None


def game_paths(args, cell, tag, arm):
    label = f'gate_{tag}_{arm}'
    result = args.out / label / f'{cell}_{label}_4/games.jsonl'
    frames = args.out / label / 'frames'
    frame_label = f'{cell}_{label}_fast_search'
    # The profiled baseline is a complete teacher game with the very same frozen
    # inputs. Reuse its raw evidence, rather than play the same game a second time.
    if tag == 'old' and arm == 'teacher' and cell != 'conveyor':
        for profile_tag in ('profile_complete', 'profile'):
            candidate = args.out / profile_tag / f'{cell}_{profile_tag}_4/games.jsonl'
            if candidate.is_file() and len(candidate.read_text().splitlines()) == 4:
                return candidate, args.out / profile_tag / 'frames', f'{cell}_{profile_tag}_fast_search'
    return result, frames, frame_label


def verify(args):
    from pvz_frame_store import read_frames
    from task70_redeploy_gate import COMPARE_FIELDS
    manifest = json.loads((args.out / 'manifest.json').read_text())
    evidence = {'games': [], 'pass': True, 'expected_pairs': 48}
    for cell, task_id in CELLS.items():
        seeds = next(t['seeds'] for t in manifest['tasks'] if t['task_id'] == task_id)
        if len(seeds) != 8:
            raise ValueError('each family must contain exactly eight seeds')
        for arm, indices in (('teacher', range(4)), ('student', range(4, 8))):
            rows = {}
            for tag in ('old', 'new'):
                path, _, _ = game_paths(args, cell, tag, arm)
                loaded = [json.loads(line) for line in path.read_text().splitlines()]
                rows[tag] = {r['seed']: r for r in loaded}
                if len(loaded) != 4 or set(rows[tag]) != {seeds[i] for i in indices}:
                    raise ValueError(f'missing, extra or duplicate games: {path}')
            for index in indices:
                seed = seeds[index]
                a, b = rows['old'][seed], rows['new'][seed]
                fields = list(COMPARE_FIELDS) + ['rollout_batches', 'rollout_lanes',
                    'halving_candidates', 'halving_rollouts', 'halving_selected_lanes',
                    'student_candidate_added', 'student_candidate_best',
                    'student_candidate_override', 'override_kinds']
                changed = [key for key in fields if a.get(key) != b.get(key)]
                frames = {}
                for tag in ('old', 'new'):
                    _, frame_root, frame_label = game_paths(args, cell, tag, arm)
                    path = frame_root / f'seed_{seed}' / frame_label / 'frames.npz'
                    frames[tag] = read_frames(path)
                    if len(frames[tag]) != rows[tag][seed]['decisions'] + 1:
                        raise ValueError(f'incomplete decision archive: {path}')
                mismatch = compare_frames(frames['old'], frames['new'])
                ok = not changed and mismatch is None
                evidence['pass'] &= ok
                evidence['games'].append(dict(cell=cell, arm=arm, seed=seed, pass_=ok,
                    changed=changed, frame_mismatch=mismatch, decisions=a['decisions'],
                    state_hash_same=a.get('state_hash') == b.get('state_hash')))
    save(args.out / 'gate_evidence.json', evidence)
    if not evidence['pass'] or len(evidence['games']) != evidence['expected_pairs']:
        raise RuntimeError('bit identity gate failed')
    print('48/48 game pairs and complete decision archives identical', flush=True)


def gate(args):
    if args.candidate is None or not args.candidate.is_file():
        raise ValueError('--candidate executable is required')
    for tag in ('old', 'new'):
        for cell in CELLS:
            for arm, beta, offset in (('teacher', 1., 0), ('student', 0., 4)):
                label = f'gate_{tag}_{arm}'
                path, _, _ = game_paths(args, cell, tag, arm)
                if tag == 'old' and arm == 'teacher' and path.is_file():
                    print(f'reuse full profiled baseline: {path}', flush=True)
                    save(args.out / label / f'{cell}_reused.json',
                         {'source': str(path), 'sha256': digest(path)})
                    continue
                cmd = command(args, cell, label, 4, beta=beta, offset=offset,
                    engine=args.candidate if tag == 'new' else None,
                    source=ROOT if tag == 'new' else args.out / 'baseline')
                save(args.out / label / f'{cell}_command.json', cmd)
                run(cmd, args.out / label / f'{cell}.log')
    verify(args)


def paired_interval(ratios, draws=10000):
    if not ratios or any(not math.isfinite(r) or r <= 0 for r in ratios):
        raise ValueError('positive finite paired timings required')
    logs = [math.log(r) for r in ratios]
    rng = random.Random(77)
    means = sorted(math.exp(statistics.mean(rng.choices(logs, k=len(logs))))
                   for _ in range(draws))
    return {'geomean': math.exp(statistics.mean(logs)), 'median': statistics.median(ratios),
            'bootstrap95': [means[int(draws * .025)], means[int(draws * .975)]]}


def load_snapshot():
    processes = {}
    for directory in Path('/proc').glob('[0-9]*'):
        try:
            fields = (directory / 'stat').read_text().rsplit(')', 1)[1].split()
            cmd = (directory / 'cmdline').read_bytes().replace(b'\0', b' ').decode(errors='replace')
            processes[int(directory.name)] = (int(fields[1]), cmd)
        except (OSError, ValueError, IndexError):
            continue
    controllers = {pid for pid, (_, cmd) in processes.items()
                   if '/cq/scripts/curriculum_queue.py' in cmd and 'python' in cmd}
    descendants = set(controllers)
    while True:
        expanded = descendants | {pid for pid, (parent, _) in processes.items() if parent in descendants}
        if expanded == descendants:
            break
        descendants = expanded
    return {'loadavg': Path('/proc/loadavg').read_text().strip(), 'qc_controllers': sorted(controllers),
            'qc_engines': sum('pvz-portable -env ' in processes[p][1] for p in descendants),
            'all_engines': sum('pvz-portable -env ' in cmd for _, cmd in processes.values())}


def abba(args):
    if args.candidate is None or not args.candidate.is_file():
        raise ValueError('--candidate executable is required')
    evidence = {'order': ['A', 'B', 'B', 'A'], 'games': [], 'load': []}
    for cell in CELLS:
        count = 2 if cell in ('roof', 'fog') else 3
        rows = []
        for index, arm in enumerate(evidence['order']):
            label = f'abba_{index}_{arm}'
            cmd = command(args, cell, label, count,
                engine=args.candidate if arm == 'B' else None,
                source=ROOT if arm == 'B' else args.out / 'baseline')
            load = {'cell': cell, 'index': index, 'before': load_snapshot()}
            evidence['load'].append(load)
            save(args.out / label / f'{cell}_command.json', cmd)
            run(cmd, args.out / label / f'{cell}.log')
            load['after'] = load_snapshot()
            path = args.out / label / f'{cell}_{label}_{count}/games.jsonl'
            data = [json.loads(line) for line in path.read_text().splitlines()]
            if len(data) != count or len({r['seed'] for r in data}) != count:
                raise ValueError(f'incomplete ABBA block: {path}')
            rows.append({r['seed']: r for r in data})
        if any(set(r) != set(rows[0]) for r in rows):
            raise ValueError('ABBA seed sets differ')
        for seed in rows[0]:
            old = statistics.mean(rows[i][seed]['seconds'] for i in (0, 3))
            new = statistics.mean(rows[i][seed]['seconds'] for i in (1, 2))
            if old <= 0 or new <= 0:
                raise ValueError('nonpositive game timing')
            evidence['games'].append(dict(cell=cell, seed=seed, old=old, new=new, ratio=new / old))
        save(args.out / 'abba_progress.json', evidence)
    evidence['summary'] = paired_interval([r['ratio'] for r in evidence['games']])
    evidence['by_cell'] = {cell: paired_interval([r['ratio'] for r in evidence['games']
                                               if r['cell'] == cell]) for cell in CELLS}
    save(args.out / 'abba_evidence.json', evidence)
    print(json.dumps(evidence['summary']), flush=True)



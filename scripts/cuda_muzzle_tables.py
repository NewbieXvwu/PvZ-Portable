"""Extract the three shooters' verified numerical stem tracks for Plant::GetPeaHeadOffset."""
import argparse
import hashlib
from pathlib import Path

from cuda_animation_tables import run_dump


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pak", type=Path, required=True)
    parser.add_argument("--dump", type=Path, default=Path("build/reanim_dump"))
    parser.add_argument("--out", type=Path, default=Path("cuda/MuzzleTables.h"))
    args = parser.parse_args()
    lines = ["// Generated by scripts/cuda_muzzle_tables.py; numerical stem coordinates only.",
             "// main.pak SHA256: " + hashlib.sha256(args.pak.read_bytes()).hexdigest(),
             "#ifndef PVZ_MUZZLE_TABLES_H", "#define PVZ_MUZZLE_TABLES_H", "namespace pvzc {"]
    def literal(value):
        token = format(value, ".9g")
        return token + ("f" if "." in token or "e" in token else ".0f")
    for seed, asset in ((0, "PeaShooterSingle"), (5, "SnowPea"), (7, "PeaShooter")):
        dump = run_dump(args.dump, args.pak, asset, "--ground", "anim_stem", "--rate", "18", "anim_idle")
        if not dump["identical"]:
            raise RuntimeError(f"{asset}: XML/compiled definitions disagree")
        (clip,) = dump["clips"]
        if (clip["start"], clip["count"]) != (4, 25):
            raise RuntimeError(f"{asset}: unsupported body clip")
        if len(clip["xy"]) != 25:
            raise RuntimeError(f"{asset}: incomplete stem track")
        rows = [(frame, x, y) for frame, (x, y) in enumerate(clip["xy"], start=4)]
        for axis in (0, 1):
            name = f"stem{seed}_{axis}"
            values = ", ".join(literal(row[axis + 1]) for row in rows)
            lines += [f"#define PVZ_STEM {{ {values} }}",
                      f"inline constexpr float {name}Host[] = PVZ_STEM;",
                      "#ifdef __CUDACC__", f"__device__ __constant__ float {name}Device[] = PVZ_STEM;",
                      "#endif", "#undef PVZ_STEM"]
    lines += ["PVZ_SIM float StemCoordinate(int type, int axis, int frame) {",
              "  if (frame < 0 || frame >= 25) return 0.0f;", "#ifdef __CUDA_ARCH__"]
    for suffix in ("Device", "Host"):
        if suffix == "Host":
            lines.append("#else")
        for seed in (0, 5, 7):
            lines.append(f"  if (type == {seed}) return axis ? stem{seed}_1{suffix}[frame] : stem{seed}_0{suffix}[frame];")
    lines += ["#endif", "  return 0.0f;", "}", "} // namespace pvzc", "#endif", ""]
    args.out.write_text("\n".join(lines))
    print(f"wrote 3 stem tracks / 150 coordinates to {args.out}")


if __name__ == "__main__":
    main()
